// Generates the twenty extra dark themes from compact definitions, so the CSS and the theme picker swatches
// always agree. Run: node scripts/make-themes.cjs   (writes src/lib/themes.json and src/app/themes-extra.css)
const fs = require('fs');
const path = require('path');

// id, label, background hue, background saturation %, accent hue, accent saturation %, accent lightness %
const DEFS = [
  ['obsidian', 'Obsidian Calm', 215, 12, 200, 45, 70],
  ['deepteal', 'Deep Teal', 185, 30, 172, 42, 66],
  ['aurora', 'Northern Aurora', 165, 22, 150, 45, 68],
  ['arctic', 'Arctic Twilight', 205, 26, 195, 55, 72],
  ['indigo', 'Indigo Dusk', 240, 26, 228, 60, 76],
  ['plum', 'Plum Velvet', 295, 22, 310, 38, 74],
  ['amethyst', 'Amethyst Night', 270, 24, 262, 50, 76],
  ['wine', 'Wine Cellar', 345, 24, 350, 50, 72],
  ['ember', 'Ember Charcoal', 18, 10, 16, 62, 68],
  ['copper', 'Copper Night', 24, 20, 26, 52, 66],
  ['olive', 'Olive Grove', 85, 16, 80, 36, 66],
  ['moss', 'Moss Stone', 110, 14, 120, 30, 66],
  ['cedar', 'Cedar Wood', 32, 20, 36, 42, 64],
  ['graphite', 'Graphite Blue', 218, 6, 214, 38, 72],
  ['ink', 'Ink Navy', 225, 40, 210, 52, 70],
  ['charmint', 'Charcoal Mint', 160, 8, 158, 40, 70],
  ['storm', 'Storm Cloud', 200, 12, 205, 30, 72],
  ['mrose', 'Midnight Rose', 330, 20, 335, 45, 74],
  ['dgold', 'Dusk Gold', 42, 16, 44, 55, 66],
  ['space', 'Space Violet', 252, 34, 268, 55, 76],
];

function hsl(h, s, l) {
  s /= 100; l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return '#' + [f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('');
}

const themes = DEFS.map(([id, label, h, s, ah, as, al]) => {
  const v = {
    bg: hsl(h, s, 7), bg2: hsl(h, s, 9.5), card: hsl(h, s, 12.5), elev: hsl(h, s, 16),
    text: hsl(h, 22, 93), text2: hsl(h, 11, 68), text3: hsl(h, 9, 48),
    accent: hsl(ah, as, al), accentInk: hsl(ah, 55, 9),
  };
  return { id, label, mode: 'dark', swatch: [v.bg, v.card, v.accent], vars: v };
});

const sel = themes.map((t) => `html[data-theme="${t.id}"]`).join(', ');
let css = '/* Generated by scripts/make-themes.cjs - do not edit by hand. Twenty extra dark themes. */\n';
css += `${sel} {\n  color-scheme: dark;\n  --border: rgba(255, 255, 255, 0.07); --border-strong: rgba(255, 255, 255, 0.14);\n  --shadow: 0 1px 0 rgba(255, 255, 255, 0.03) inset, 0 10px 28px -14px rgba(0, 0, 0, 0.6);\n  --glass: rgba(0, 0, 0, 0.25); --hover: rgba(255, 255, 255, 0.05); --heat0: rgba(255, 255, 255, 0.05);\n}\n`;
for (const t of themes) {
  const v = t.vars;
  css += `html[data-theme="${t.id}"] { --bg: ${v.bg}; --bg2: ${v.bg2}; --card: ${v.card}; --elev: ${v.elev}; --text: ${v.text}; --text2: ${v.text2}; --text3: ${v.text3}; --accent: ${v.accent}; --accent-ink: ${v.accentInk}; }\n`;
}
const root = path.join(__dirname, '..');
fs.writeFileSync(path.join(root, 'src/app/themes-extra.css'), css);
fs.writeFileSync(path.join(root, 'src/lib/themes.json'), JSON.stringify(themes.map(({ id, label, mode, swatch }) => ({ id, label, mode, swatch })), null, 2) + '\n');
console.log(`wrote ${themes.length} themes`);
